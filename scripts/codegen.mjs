import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { z } from 'zod';
import { compile } from 'json-schema-to-typescript';
import { Plan } from '../src/plan.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
if (args.some(arg => arg !== '--check')) throw new Error('Usage: node scripts/codegen.mjs [--check]');
const check = args.includes('--check');
const files = new Map();
const banner = '/* Generated by npm run generate from src/plan.mjs. Do not edit.\n' +
  ' * Structural types only; Plan.parse and validatePlanForExecution remain required. */';

for (const [io, name] of [['input', 'TutorialPlanInput'], ['output', 'TutorialPlan']]) {
  const schema = z.toJSONSchema(Plan, { io, target: 'draft-7' });
  schema.title = name;
  schema.description = 'Structural tutorial plan contract. Custom Zod refinements (URL policy, even viewport dimensions, action requirements and graph integrity) and execution approval are enforced at runtime, not by this schema.';
  const stem = io === 'input' ? 'tutorial-plan.input' : 'tutorial-plan';
  files.set(`schemas/${stem}.schema.json`, JSON.stringify(schema, null, 2) + '\n');
  files.set(`types/generated/${stem}.d.ts`, await compile(schema, name, {
    bannerComment: banner,
    // Keep bounded step arrays readable; runtime Zod enforces their length.
    ignoreMinAndMaxItems: true,
    style: { singleQuote: true, semi: true, tabWidth: 2 },
  }));
}

let stale = false;
for (const [relative, content] of files) {
  const filename = path.join(root, relative);
  if (check) {
    const current = await readFile(filename, 'utf8').catch(error => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (current !== content) {
      console.error(`Generated file is missing or stale: ${relative}`);
      stale = true;
    }
  } else {
    await mkdir(path.dirname(filename), { recursive: true });
    await writeFile(filename, content);
    console.log(`Generated ${relative}`);
  }
}
if (stale) {
  console.error('Run npm run generate and commit the generated files.');
  process.exitCode = 1;
}
