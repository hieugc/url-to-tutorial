import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { consolidateBranches } from '../scripts/consolidate-branches.mjs';

test('Branch consolidation keeps unaudited/unmerged/moved heads and atomically deletes audited history', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'utv-branches-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const cwd = path.join(root, 'work');
  const remote = path.join(root, 'remote.git');
  await mkdir(cwd);
  const git = (...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git('init', '--bare', remote);
  git('init', '-b', 'main');
  git('config', 'user.email', 'test@example.invalid');
  git('config', 'user.name', 'Consolidation test');
  git('commit', '--allow-empty', '-m', 'base');
  git('remote', 'add', 'origin', remote);
  git('checkout', '-b', 'feat/audited');
  git('commit', '--allow-empty', '-m', 'feature');
  const audited = git('rev-parse', 'HEAD');
  git('checkout', 'main');
  git('push', 'origin', 'main', 'feat/audited');
  const manifest = { 'feat/audited': audited };
  assert.throws(() => consolidateBranches(manifest, { cwd, apply: true }), /not in remote main/);
  assert.throws(() => consolidateBranches({ main: audited }, { cwd, apply: true }), /Invalid audited/);
  git('merge', '--ff-only', 'feat/audited');
  git('branch', 'feat/keep');
  git('push', 'origin', 'main', 'feat/keep');
  assert.deepEqual(consolidateBranches(manifest, { cwd }).branches, ['feat/audited']);
  assert.match(git('ls-remote', '--heads', 'origin'), /refs\/heads\/feat\/audited/);
  assert.throws(() => consolidateBranches({ 'feat/audited': '0'.repeat(40) }, { cwd, apply: true }), /changed since audit/);
  assert.deepEqual(consolidateBranches(manifest, { cwd, apply: true }).branches, ['feat/audited']);
  const refs = git('ls-remote', '--heads', 'origin');
  assert.doesNotMatch(refs, /refs\/heads\/feat\/audited/);
  assert.match(refs, /refs\/heads\/main/);
  assert.match(refs, /refs\/heads\/feat\/keep/);
  assert.deepEqual(consolidateBranches(manifest, { cwd, apply: true }).branches, []);
});
